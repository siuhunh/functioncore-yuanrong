// Package uuid for common functions
package uuid

import (
	"crypto/rand"
	"crypto/sha1"
	"encoding/hex"
	"errors"
	"hash"
	"io"
	"strings"
)

const (
	defaultUUIDLength      = 16
	defaultUUIDStrLen      = 36
	defaultSHA1BaseVersion = 5
)

// UUID is a 128 bit (16 byte) Universal Unique IDentifier as defined in RFC 4122.
type UUID [defaultUUIDLength]byte

var (
	rander = rand.Reader // random function
	// NameSpaceURL Well known namespace IDs and UUIDs
	NameSpaceURL, _ = parseUUID("6ba7b811-9dad-11d1-80b4-00c04fd430c8")
)

// New creates a new random UUID or panics.  New is equivalent to the expression.
func New() UUID {
	return Must(NewRandom())
}

// Must returns uuid if err is nil and panics otherwise.
func Must(result UUID, err error) UUID {
	if err != nil {
		panic(err)
	}
	return result
}

// NewRandom returns a Random (Version 4) UUID.
func NewRandom() (UUID, error) {
	return NewRandomFromReader(rander)
}

// NewRandomFromReader returns a UUID based on bytes read from a given io.Reader.
func NewRandomFromReader(r io.Reader) (UUID, error) {
	var result UUID
	_, err := io.ReadFull(r, result[:])
	if err != nil {
		return UUID{}, err
	}
	// Set the version to 4 (randomly generated UUID).
	result[6] = (result[6] & 0x0f) | 0x40 // The version bits are at positions 6 and 7.
	// Set the variant to 10 (RFC 4122 variant).
	result[8] = (result[8] & 0x3f) | 0x80 // The variant bits are at positions 8, 9, and 10 (counting from 0).
	return result, nil
}

// String returns the string form of uuid, xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx
// , or "" if uuid is invalid.
func (uuid UUID) String() string {
	var dst [defaultUUIDStrLen]byte
	encodeHex(dst[:], uuid)
	return string(dst[:])
}

func encodeHex(buf []byte, uuid UUID) {
	hex.Encode(buf, uuid[:4]) // Encode the first 4 bytes of the UUID into the first 8 bytes of buf.
	buf[8] = '-'              // Insert the first hyphen at the correct position.

	hex.Encode(buf[9:13], uuid[4:6]) // Encode bytes 5 and 6 of the UUID into bytes 9 to 12 of buf.
	buf[13] = '-'                    // Insert the second hyphen at the correct position.

	hex.Encode(buf[14:18], uuid[6:8]) // Encode bytes 7 and 8 of the UUID into bytes 14 to 17 of buf.
	buf[18] = '-'                     // Insert the third hyphen at the correct position.

	hex.Encode(buf[19:23], uuid[8:10]) // Encode bytes 9 and 10 of the UUID into bytes 19 to 22 of buf.
	buf[23] = '-'                      // Insert the fourth hyphen at the correct position.

	hex.Encode(buf[24:], uuid[10:]) // Encode the last 6 bytes of the UUID into bytes 24 to 35 of buf
}

// NewSHA1 returns a new SHA1 UUID based on the
// supplied name space and data.
func NewSHA1(space UUID, data []byte) UUID {
	return NewHash(sha1.New(), space, data, defaultSHA1BaseVersion)
}

// NewHash returns a new UUID derived from the hash of space concatenated with
// data generated by h.  The hash should be at least 16 byte in length.  The
// first 16 bytes of the hash are used to form the UUID.
func NewHash(sha1Hash hash.Hash, space UUID, data []byte, version int) UUID {
	sha1Hash.Reset()
	sha1Hash.Write(space[:])
	sha1Hash.Write(data)
	s := sha1Hash.Sum(nil)
	var uuid UUID
	copy(uuid[:], s)
	// Set the version bits in the UUID.
	uuid[6] = (uuid[6] & 0x0f) | uint8((version&0xf)<<4) // The version bits are located at positions 13-15.
	// Set the variant bits in the UUID.
	uuid[8] = (uuid[8] & 0x3f) | 0x80 // The variant bits are located at positions 8-11 (counting from 0).
	return uuid
}

func parseUUID(uuidStr string) (UUID, error) {
	const separator = "-"

	uuidStr = strings.ReplaceAll(uuidStr, separator, "")

	if len(uuidStr) != 32 { // Check if the length of the UUID string is exactly 32 characters (16 bytes).
		return UUID{}, errors.New("invalid UUID length")
	}

	part1, part2 := uuidStr[:16], uuidStr[16:] // Split the UUID string into two parts, each representing 8 bytes.

	b1, err := hex.DecodeString(part1)
	if err != nil {
		return UUID{}, err
	}
	b2, err := hex.DecodeString(part2)
	if err != nil {
		return UUID{}, err
	}

	var uuid UUID
	copy(uuid[:8], b1) // Copy the first 8 bytes into the UUID variable.
	copy(uuid[8:], b2) // Copy the remaining 8 bytes into the UUID variable.

	return uuid, nil
}
